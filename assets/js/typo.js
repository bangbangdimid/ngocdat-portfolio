/* ============================================================
   typo.js - line-break hygiene for Vietnamese text (window.Typo)

   Vietnamese is written in single syllables separated by spaces, so a browser
   happily breaks "toàn / quốc" or "TP. Hồ Chí / Minh", or leaves one syllable
   alone on the last line. This joins the syllables that belong together with
   a no-break space, so a line can only break BETWEEN words:
     1. words of several syllables, from the list in vi-words.js
        (generated by tools/build-words.js; longest match wins)
     2. names and set phrases (TP. Hồ Chí Minh, Huy chương Vàng ...)
     3. numbers with the word they belong to (lớp 10, Toán 9, 6-12, 25 trang)
     4. the last two words of every paragraph / heading (no one-word last line)
   It only rewrites text nodes, so markup, links and events are untouched.
   Typo.apply(root) can be called again after content is rendered dynamically.
   ============================================================ */
(function () {
  const NB = "\u00a0";
  const WJ = String.fromCharCode(0x2060); // word joiner: forbids a break and renders nothing
  const MAX_SYLLABLES = 4;
  const glued = new WeakSet(); // text nodes whose last word is already glued: apply() may run many times, blocks may nest

  // multi-syllable words: "toàn quốc", "bản chất", "bài kiểm tra" ...
  const WORDS = new Set((window.VI_WORDS || "").split("|").filter(Boolean));

  // names and phrases the word list cannot express (capitalised, with hyphens or commas)
  const KEEP = [
    "TP. Hồ Chí Minh", "Hồ Chí Minh", "Đại học Ngoại thương", "Phổ thông Năng khiếu", "Tài chính - Ngân hàng",
    "Lê Hồng Phong", "THPT chuyên", "Olympic Toán học", "Sinh viên", "Giải Nhất", "Giải Ba",
    "Huy chương Bạc", "Huy chương Đồng", "Huy chương Vàng", "Ngày Nhà giáo", "Việt Nam",
    "Toán học", "Toán cơ bản", "HSG Toán", "chuyên Tin", "chuyên Toán", "Chuyên Tin", "Chuyên Toán",
    "Lớp Toán", "anh Đạt", "Ngọc Đạt", "Quang Khôi", "Đông Nghi", "Hải Đăng", "Cloudflare",
    "AMC, AMO, IKMC", "AMC, AMO", "AMC và AMO", "PiiSE - PTNK",
  ].map((p) => ({
    re: new RegExp(p.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/ /g, " +"), "g"),
    // a hyphen allows a break right after it even before a no-break space, so add a word joiner
    to: p.replace(/ - /g, NB + "-" + WJ + NB).replace(/ /g, NB),
  }));

  // block-level elements whose last two words are kept together
  const BLOCKS = "p, li, dd, dt, h1, h2, h3, h4, figcaption, blockquote, label, .badge, .tag, .for, .sub, .lede, .hint, .muted, .name, .level, .hand";
  const SKIP = "script, style, textarea, pre, code, [data-notypo], .pdf-pages";

  function textNodes(root) {
    const list = [];
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: (n) => (n.nodeValue.trim() && !(n.parentElement && n.parentElement.closest(SKIP))) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT,
    });
    while (w.nextNode()) list.push(w.currentNode);
    return list;
  }

  // "Cực hạn, bất biến" -> binds "cực hạn" and "bất biến": longest dictionary word first
  function bindWords(text) {
    if (!WORDS.size) return text;
    return text.replace(/\p{L}+(?: \p{L}+)+/gu, (run) => {
      const syl = run.split(" "), low = syl.map((s) => s.toLowerCase());
      const out = [];
      for (let i = 0; i < syl.length;) {
        let n = Math.min(MAX_SYLLABLES, syl.length - i);
        while (n > 1 && !WORDS.has(low.slice(i, i + n).join(" "))) n--;
        out.push(syl.slice(i, i + n).join(NB));
        i += n;
      }
      return out.join(" ");
    });
  }

  function bind(text) {
    let s = text;
    for (const k of KEEP) s = s.replace(k.re, k.to);
    s = bindWords(s);
    s = s.replace(/(\d)-(?=\d)/g, "$1-" + WJ);                       // 6-12, 1-2 phút: no break after the hyphen
    s = s.replace(/(\p{L}|\.) (?=\d)/gu, "$1" + NB);                 // lớp 10, Toán 9, thứ 31, TP. 3
    s = s.replace(/(\d) (?=\p{L}{1,8}(?![\p{L}\d]))/gu, "$1" + NB);  // 25 trang, 17 chuyên
    return s;
  }

  // glue the last word (a group of syllables already joined by no-break spaces) to the one before it
  function glueLastWord(s) {
    const t = s.replace(/ +$/, "");
    const i = t.lastIndexOf(" ");
    return i < 1 ? s : t.slice(0, i) + NB + t.slice(i + 1) + s.slice(t.length);
  }

  function apply(root) {
    const scope = root || document.body;
    textNodes(scope).forEach((n) => { const t = bind(n.nodeValue); if (t !== n.nodeValue) n.nodeValue = t; });
    // the italic part of a heading ("lặn sâu", "lớp học") is one phrase: never split it
    scope.querySelectorAll("h1 em, h2 em, h3 em").forEach((em) =>
      textNodes(em).forEach((n) => { n.nodeValue = n.nodeValue.replace(/ /g, NB); }));
    const blocks = scope.matches && scope.matches(BLOCKS) ? [scope] : [];
    blocks.push(...scope.querySelectorAll(BLOCKS));
    blocks.forEach((el) => {
      if (el.closest(SKIP)) return;
      const nodes = textNodes(el);
      const last = nodes[nodes.length - 1];
      // needs at least three words so the head of the sentence is not glued together
      if (!last || glued.has(last)) return;
      glued.add(last);
      if (el.textContent.trim().split(" ").length >= 3) last.nodeValue = glueLastWord(last.nodeValue);
    });
  }

  window.Typo = { apply };
  apply();
})();
