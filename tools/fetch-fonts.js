#!/usr/bin/env node
/* ============================================================
   fetch-fonts.js - self-host the web fonts (run once, or to change weights)

   Downloads the Vietnamese and Latin subsets of the fonts the site uses from
   Google Fonts into assets/fonts/ and writes assets/css/fonts.css.
   Why: every visitor then gets exactly the same font files from our own
   domain (same letter widths on every device, no third-party request, no
   layout shift from a late CDN), and the CSP can drop fonts.googleapis.com.
   All three families are licensed under the SIL Open Font License 1.1.

       node tools/fetch-fonts.js
   ============================================================ */
const fs = require("fs");
const path = require("path");
const https = require("https");
const crypto = require("crypto");

const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT, "assets/fonts");
const OUT_CSS = path.join(ROOT, "assets/css/fonts.css");
const SUBSETS = new Set(["vietnamese", "latin"]);
const CSS_URL = "https://fonts.googleapis.com/css2?family=Be+Vietnam+Pro:wght@400;500;600;700" +
  "&family=Cormorant+Garamond:ital,wght@0,500;0,600;1,500&family=Patrick+Hand&display=swap";
// Google serves woff2 only to a modern browser user agent
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

function get(url) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { "User-Agent": UA } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) return resolve(get(res.headers.location));
      if (res.statusCode !== 200) return reject(new Error("HTTP " + res.statusCode + " for " + url));
      const chunks = [];
      res.on("data", (c) => chunks.push(c));
      res.on("end", () => resolve(Buffer.concat(chunks)));
    }).on("error", reject);
  });
}

(async () => {
  const css = (await get(CSS_URL)).toString("utf8");
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
  const faces = [];
  let bytes = 0;
  for (const [, subset, body] of blocks) {
    if (!SUBSETS.has(subset)) continue;
    const family = /font-family:\s*'([^']+)'/.exec(body)[1];
    const style = /font-style:\s*(\w+)/.exec(body)[1];
    const weight = /font-weight:\s*(\d+)/.exec(body)[1];
    const url = /src:\s*url\(([^)]+)\)/.exec(body)[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)[1].trim();
    const data = await get(url);
    // a variable font is served once per weight: identical files become one face with a weight range
    const key = [family, style, subset, crypto.createHash("md5").update(data).digest("hex")].join("|");
    const same = faces.find((x) => x.key === key);
    if (same) { same.weights.push(+weight); continue; }
    faces.push({ key, family, style, weights: [+weight], subset, range, data });
  }
  for (const f of faces) {
    const lo = Math.min(...f.weights), hi = Math.max(...f.weights);
    f.weight = lo === hi ? String(lo) : lo + " " + hi;
    f.file = [f.family.toLowerCase().replace(/\s+/g, "-"), lo === hi ? lo : lo + "-" + hi, f.style === "italic" ? "italic" : null, f.subset].filter(Boolean).join("-") + ".woff2";
    fs.writeFileSync(path.join(OUT_DIR, f.file), f.data);
    bytes += f.data.length;
  }
  const header = "/* GENERATED by tools/fetch-fonts.js - do not edit by hand.\n" +
    "   Be Vietnam Pro, Cormorant Garamond and Patrick Hand, SIL Open Font License 1.1.\n" +
    "   Only the Vietnamese and Latin subsets are shipped; the browser downloads a file\n" +
    "   only when a character of its unicode-range appears on the page. */\n";
  const rules = faces.map((f) => `@font-face {\n  font-family: "${f.family}";\n  font-style: ${f.style};\n  font-weight: ${f.weight};\n  font-display: swap;\n  src: url("../fonts/${f.file}") format("woff2");\n  unicode-range: ${f.range};\n}`).join("\n");
  fs.writeFileSync(OUT_CSS, header + rules + "\n");
  console.log("fonts:", faces.length, "files,", Math.round(bytes / 1024), "KB ->", path.relative(ROOT, OUT_DIR), "and", path.relative(ROOT, OUT_CSS));
})().catch((e) => { console.error(e); process.exit(1); });
